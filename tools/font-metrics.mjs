// Writes src/data/fontmetrics.ts: the advance widths of Liberation Serif, the
// font the mission book sets its tables in, for the characters scenario text
// uses. The LaTeX writer estimates how many lines a table cell takes from
// them, without a browser. Run: node tools/font-metrics.mjs

import { readFileSync, writeFileSync } from "node:fs";

const FONTS = { normal: "Regular", bold: "Bold", italic: "Italic", bolditalic: "BoldItalic" };
// Printable ASCII and the typographic characters the markup produces.
const CHARS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ..."\u00a0\u2013\u2014\u201c\u201d\u2018\u2019\u00d7\u00a7\u2026\u00e9\u00fc\u00f6\u00e4"];

function tables(buf) {
  const count = buf.readUInt16BE(4);
  const out = {};
  for (let i = 0; i < count; i++) {
    const at = 12 + i * 16;
    out[buf.toString("latin1", at, at + 4)] = buf.readUInt32BE(at + 8);
  }
  return out;
}

/** Glyph index of each code point, from the Unicode BMP subtable (format 4). */
function cmap4(buf, start) {
  const n = buf.readUInt16BE(start + 2);
  for (let i = 0; i < n; i++) {
    const rec = start + 4 + i * 8;
    const platform = buf.readUInt16BE(rec);
    const encoding = buf.readUInt16BE(rec + 2);
    const sub = start + buf.readUInt32BE(rec + 4);
    if (platform === 3 && encoding === 1 && buf.readUInt16BE(sub) === 4) {
      const segs = buf.readUInt16BE(sub + 6) / 2;
      const ends = sub + 14;
      const starts = ends + segs * 2 + 2;
      const deltas = starts + segs * 2;
      const offsets = deltas + segs * 2;
      return (code) => {
        for (let s = 0; s < segs; s++) {
          if (code > buf.readUInt16BE(ends + s * 2)) continue;
          if (code < buf.readUInt16BE(starts + s * 2)) return 0;
          const delta = buf.readInt16BE(deltas + s * 2);
          const offset = buf.readUInt16BE(offsets + s * 2);
          if (!offset) return (code + delta) & 0xffff;
          const glyph = buf.readUInt16BE(offsets + s * 2 + offset + (code - buf.readUInt16BE(starts + s * 2)) * 2);
          return glyph ? (glyph + delta) & 0xffff : 0;
        }
        return 0;
      };
    }
  }
  throw new Error("no Unicode BMP cmap");
}

function widths(file) {
  const buf = readFileSync(new URL(`../public/assets/fonts/LiberationSerif-${file}.ttf`, import.meta.url));
  const t = tables(buf);
  const unitsPerEm = buf.readUInt16BE(t.head + 18);
  const metrics = buf.readUInt16BE(t.hhea + 34);
  const glyphOf = cmap4(buf, t.cmap);
  const advance = (glyph) => buf.readUInt16BE(t.hmtx + Math.min(glyph, metrics - 1) * 4);
  return CHARS.map((ch) => Math.round((advance(glyphOf(ch.codePointAt(0))) / unitsPerEm) * 1000));
}

const lines = Object.entries(FONTS).map(([style, file]) => `  ${style}: [${widths(file).join(", ")}],`);
const source = `// Generated by tools/font-metrics.mjs from the Liberation Serif fonts in
// public/assets/fonts (SIL Open Font License). Do not edit by hand.

/** The characters measured, in the order of the width lists. */
export const METRIC_CHARS = ${JSON.stringify(CHARS.join(""))};

/** Advance widths in thousandths of an em, per style, in METRIC_CHARS order. */
export const LIBERATION_SERIF: Record<"normal" | "bold" | "italic" | "bolditalic", readonly number[]> = {
${lines.join("\n")}
};
`;
writeFileSync(new URL("../src/data/fontmetrics.ts", import.meta.url), source);
console.log("wrote src/data/fontmetrics.ts");
